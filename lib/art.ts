import artData from "@/lib/art.json";

export const ART_SECTIONS = [
  { key: "watercolor", label: "Watercolor" },
  { key: "oil", label: "Oil painting" },
  { key: "pencil", label: "Pencil & marker" },
  { key: "charcoal", label: "Charcoal" },
  { key: "mixed", label: "Mixed media" },
] as const;

export type ArtSection = (typeof ART_SECTIONS)[number]["key"];

export type ArtPiece = {
  id: string;
  post: string;
  date: string;
  src: string;
  thumb: string;
  width: number;
  height: number;
  color: string;
  title: string;
  medium: string;
  section: ArtSection;
  version?: string;
  // Medium view order within a section: positive pins lead (1 first),
  // negative pins trail (-1 last), everything else sits between.
  pin?: number;
};

// Generated by scripts/import-instagram-art.mjs; titles, mediums, sections, and
// pins are hand-edited in lib/art.json. Framed pieces carry a version so a
// re-cropped image isn't served from cache.
export function getArtPieces(): ArtPiece[] {
  return (artData.pieces as ArtPiece[]).map((piece) =>
    piece.version
      ? {
          ...piece,
          src: `${piece.src}?v=${piece.version}`,
          thumb: `${piece.thumb}?v=${piece.version}`,
        }
      : piece,
  );
}

function hsl(hex: string): { h: number; s: number; l: number } {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const delta = max - min;
  const l = (max + min) / 2;
  const s = delta === 0 ? 0 : delta / (1 - Math.abs(2 * l - 1));
  const h =
    delta === 0
      ? 0
      : max === r
        ? ((g - b) / delta) % 6
        : max === g
          ? (b - r) / delta + 2
          : (r - g) / delta + 4;
  return { h: (h * 60 + 360) % 360, s, l };
}

// Red → orange → yellow → green → blue → violet, with near-greys (whose hue
// is mostly noise) trailing from light to dark.
export function compareRainbow(a: string, b: string): number {
  const [x, y] = [hsl(a), hsl(b)];
  const [greyX, greyY] = [x.s < 0.12, y.s < 0.12];
  if (greyX !== greyY) {
    return greyX ? 1 : -1;
  }
  if (greyX) {
    return y.l - x.l;
  }
  // Start the wheel just below red so pinks wrap around to the front.
  return ((x.h + 20) % 360) - ((y.h + 20) % 360);
}

function pinGroup(piece: ArtPiece): number {
  return piece.pin === undefined ? 1 : piece.pin > 0 ? 0 : 2;
}

// Sections in ART_SECTIONS order: positive pins first, then the rest around
// the color wheel, then negative pins. Mixed media keeps date order so the
// comic's pages read in sequence.
export function sortBySection(pieces: ArtPiece[]): ArtPiece[] {
  const rank = new Map<string, number>(ART_SECTIONS.map(({ key }, index) => [key, index]));
  return [...pieces].sort(
    (a, b) =>
      (rank.get(a.section) ?? ART_SECTIONS.length) -
        (rank.get(b.section) ?? ART_SECTIONS.length) ||
      pinGroup(a) - pinGroup(b) ||
      (a.pin ?? 0) - (b.pin ?? 0) ||
      (a.section === "mixed" ? 0 : compareRainbow(a.color, b.color)),
  );
}
